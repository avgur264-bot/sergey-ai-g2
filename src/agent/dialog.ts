/**
 * Правила ведения разговора.
 *
 * Вынесено из main.ts намеренно: там при импорте запускается всё
 * приложение, и проверить эти правила в тестах было бы нельзя. А
 * проверять их надо — ошибка здесь либо обрывает разговор на полуслове,
 * либо не даёт его закончить.
 */

/** Ответ заканчивается вопросом — значит ждут реплику в ответ. */
export function endsWithQuestion(text: string): boolean {
  const t = text.trim();
  if (!t.endsWith('?')) return false;

  // Смотрим именно последнее ПРЕДЛОЖЕНИЕ, а не строку: риторический
  // оборот обычно завершает абзац, а не стоит отдельным абзацем.
  const last = (t.split(/(?<=[.!?])\s+/).pop() ?? t).trim();
  return !/^(почему бы|как знать|кто знает|не так ли|правда)/i.test(last);
}

/**
 * Слова, которыми человек заканчивает разговор.
 *
 * Нужны, потому что иначе контекст копится: следующий вопрос про
 * совершенно другое тянет за собой прошлую тему и сбивает ответ.
 *
 * Список намеренно узкий и требует, чтобы фраза состояла только из
 * этих слов. «Хватит ли мне денег на билет» — обычный вопрос, и
 * обрывать на нём разговор было бы обидно.
 */
const FAREWELL =
  /^(хватит|всё|все|спасибо|стоп|закончили|конец|достаточно|пока|отбой|свободен)[\s,.!]*$/i;

const FAREWELL_PAIR =
  /^(спасибо|всё|все)[\s,]+(всё|все|хватит|достаточно|пока)[\s.!]*$/i;

export function isFarewell(text: string): boolean {
  const t = text.trim().toLowerCase();
  return FAREWELL.test(t) || FAREWELL_PAIR.test(t);
}
